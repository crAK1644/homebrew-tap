  def install
    # litellm's Rust extension vendors aws-lc-sys, whose jitterentropy source
    # refuses to compile with optimizations on (`#error "... must not be compiled
    # with optimizations"`). cc-rs already passes -O0 for that file; Homebrew's
    # compiler shim appends its own -O3 afterwards and wins. Dropping the shim's
    # level lets the per-file flag stand. Only C compiles are affected -- rustc
    # still builds the crates themselves in release mode.
    ENV.O0

    # A Python extension module resolves `_PyExc_*` from the interpreter that
    # loads it, so it must link with `-undefined dynamic_lookup`. pyo3 asks for
    # that flag itself; Homebrew's shim drops it, and tokenizers then fails with
    # "symbol(s) not found for architecture arm64". Put it back.
    ENV.append "RUSTFLAGS", "-C link-arg=-undefined -C link-arg=dynamic_lookup"

    virtualenv_install_with_resources
  end

